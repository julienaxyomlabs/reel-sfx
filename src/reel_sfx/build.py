"""Regenerate every bundled WAV and sounds.json from the recipes:  python -m reel_sfx.build [OUT_DIR]

Deterministic: each recipe has a fixed seed. The test-suite re-renders every sound and compares it with the
bundled file, so a recipe change that is not rebuilt (or a non-reproducible recipe) fails CI.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np

from .generators import RECIPES
from .wavio import write_wav

SR, BITS = 48000, 24
PROVENANCE = ('Generated by reel_sfx.generators (oscillators, shaped noise and envelopes written from first principles). '
              'No recording, sample, or analysis of any existing sound was used to make it.')


def build(out_dir: Path) -> list:
    out_dir.mkdir(parents=True, exist_ok=True); entries = []
    for sid in sorted(RECIPES):
        r = RECIPES[sid]; y, anc = r.fn(r.seed, SR)
        rel = f'{r.category}/{sid}.wav'; write_wav(out_dir / rel, y, SR, BITS)
        pk = float(np.abs(y).max()); rms = float(np.sqrt((y ** 2).mean()))
        entries.append({
            'id': sid, 'title': r.title, 'category': r.category, 'tags': list(r.tags), 'use': r.use, 'file': rel,
            'anchor': {'type': r.anchor, 'seconds': round(float(anc), 6)},
            'duration_s': round(len(y) / SR, 6), 'sample_rate': SR, 'channels': 2, 'bit_depth': BITS,
            'peak_dbfs': round(20 * np.log10(pk), 2), 'rms_dbfs': round(20 * np.log10(rms), 2),
            'suggested_gain_db': r.level_db,
            'generator': f'reel_sfx.generators:{r.fn.__name__}', 'seed': r.seed,
            'license': 'CC0-1.0', 'provenance': PROVENANCE,
            'sha256': hashlib.sha256((out_dir / rel).read_bytes()).hexdigest(),
        })
    (out_dir / 'sounds.json').write_text(json.dumps({'schema': 1, 'sample_rate': SR, 'license': 'CC0-1.0', 'sounds': entries},
                                                    indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    return entries


if __name__ == '__main__':
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / 'sounds'
    for e in build(out):
        print(f"{e['id']:<16} {e['duration_s']:>6.3f} s  peak {e['peak_dbfs']:>6.2f} dBFS  rms {e['rms_dbfs']:>6.1f}  {e['file']}")
